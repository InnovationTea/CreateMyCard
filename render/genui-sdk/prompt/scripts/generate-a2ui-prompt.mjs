function main() {
  if (!fs.existsSync(a2uiRoot)) {
    console.error("generate-a2ui-prompt: missing directory", a2uiRoot);
    process.exit(1);
  }

  const parts = [
    "# A2UI skill (HarmonyOS-oriented) — embedded from skills/a2ui\n\n",
  ];

  for (let i = 0; i < REL_PATHS.length; i++) {
    const rel = REL_PATHS[i];
    const abs = path.join(a2uiRoot, rel);
    if (!fs.existsSync(abs)) {
      console.error("generate-a2ui-prompt: missing file", abs);
      process.exit(1);
    }
    let body = fs.readFileSync(abs, "utf8").replace(/\r\n/g, "\n").replace(/\r/g, "\n");
    if (rel === "SKILL.md") body = stripYamlFrontmatter(body);

    if (i > 0) parts.push("\n\n---\n\n");
    parts.push(`## skills/a2ui/${rel}\n\n`);
    parts.push(body);
  }

  const bundled = parts.join("");
  const lines = [
    "// AUTO-GENERATED by scripts/generate-a2ui-prompt.mjs — do not edit",
    "",
    `export const A2UI_SKILL_PROMPT = ${JSON.stringify(bundled)} as const;`,
    "",
  ];

  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, lines.join("\n"), "utf8");
  console.log("Wrote", outFile, `(${bundled.length} chars)`);
}

main();
