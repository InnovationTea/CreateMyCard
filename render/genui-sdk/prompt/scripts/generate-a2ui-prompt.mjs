/**
 * Bundles repository skills/a2ui markdown files (ordered list) into
 * src/prompt-assets/a2ui_skill.generated.ts
 * Run from package root: node scripts/generate-a2ui-prompt.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "../../..");
const a2uiRoot = path.join(repoRoot, "skills", "a2ui");
const outFile = path.join(
  path.resolve(__dirname, ".."),
  "src",
  "prompt-assets",
  "a2ui_skill.generated.ts",
);

/** Cursor Skill YAML frontmatter — strip to save tokens */
function stripYamlFrontmatter(s) {
  const t = s.replace(/\r\n/g, "\n").replace(/\r/g, "\n");
  if (!t.startsWith("---\n")) return t;
  const end = t.indexOf("\n---\n", 4);
  if (end === -1) return t;
  return t.slice(end + 5).replace(/^\n+/, "");
}

/** Order matters: core → design → protocol → templates → runtime → styles → examples (no README.md) */
