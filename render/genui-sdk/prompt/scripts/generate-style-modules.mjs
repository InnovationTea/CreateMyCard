/**
 * Reads src/styles/*.md and writes src/prompt-assets/styles.generated.ts
 * Run from package root: node scripts/generate-style-modules.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const stylesDir = path.join(root, "src", "styles");
const outFile = path.join(root, "src", "prompt-assets", "styles.generated.ts");

function fileBaseToConstName(file) {
  const s = file.replace(/\.md$/i, "");
  const snake = s.replace(/[^a-zA-Z0-9]+/g, "_").replace(/^_|_$/g, "");
  return "STYLE_" + snake.toUpperCase();
}

function fileBaseToKey(file) {
  return file.replace(/\.md$/i, "");
}

function main() {
  if (!fs.existsSync(stylesDir)) {
    fs.mkdirSync(stylesDir, { recursive: true });
  }

  const files = fs.readdirSync(stylesDir).filter((f) => f.endsWith(".md")).sort();
  if (files.length === 0) {
    console.error(
      "generate-style-modules: no .md files in",
      stylesDir,
      "— add at least one style markdown file.",
    );
    process.exit(1);
  }

  const lines = [
    "// AUTO-GENERATED by scripts/generate-style-modules.mjs — do not edit",
    "",
  ];

  const entries = [];

  for (const file of files) {
    const abs = path.join(stylesDir, file);
    const raw = fs.readFileSync(abs, "utf8").replace(/\r\n/g, "\n").replace(/\r/g, "\n");
    const constName = fileBaseToConstName(file);
    const key = fileBaseToKey(file);
    lines.push(`export const ${constName} = ${JSON.stringify(raw)} as const;`);
    lines.push("");
    entries.push({ key, constName });
  }

  lines.push(`export const STYLE_BY_ID = {`);
  for (const { key, constName } of entries) {
    lines.push(`  ${JSON.stringify(key)}: ${constName},`);
  }
  lines.push(`} as const;`);
  lines.push(``);
  lines.push(`export type StyleId = keyof typeof STYLE_BY_ID;`);
  lines.push(``);
  const defaultKey = entries[0].key;
  lines.push(
    `/** First file in lexicographic order under src/styles/*.md */`,
  );
  lines.push(`export const DEFAULT_STYLE_ID: StyleId = ${JSON.stringify(defaultKey)};`);
  lines.push(``);

  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, lines.join("\n"), "utf8");
  console.log("Wrote", outFile, `(${entries.length} style(s))`);
}

main();
